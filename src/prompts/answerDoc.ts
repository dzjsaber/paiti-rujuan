export const ANSWER_DOC_PROMPT_VERSION = 'v1';

export const ANSWER_DOC_PROMPT = `你是答案解析器。输入是一份答案文档（可能带题型标注、注释或解释），请提取每一题的"题号"和"标准答案"，严格输出 JSON 数组，不输出其他文字。

输出格式：
[{"no": "1", "answer": "B"}, {"no": "6", "answer": "√"}]

规则：
1. 单选答案输出选项ID（如 "A"）；多选输出连续字母（如 "ABC"）；判断题输出 √ 或 ×；填空/简答输出答案文本。
2. 忽略题型标注（如"（单选）"）和答案后的解释性括号（如"（哈福/哈佛结构）"）。
3. 简答题保留完整答案文本。
4. 无法确定答案的题号跳过，不要编造。
5. 只输出 JSON 数组，不要使用 Markdown 代码围栏。`;
